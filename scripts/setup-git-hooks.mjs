#!/usr/bin/env node
/**
 * scripts/setup-git-hooks.mjs
 * Zero-dependency native Git hook installer that binds pre-commit to npm run dod:check.
 * 
 * Usage:
 *   node scripts/setup-git-hooks.mjs
 */

import fs from 'fs';
import path from 'path';

const rootDir = process.cwd();
const gitDir = path.join(rootDir, '.git');
const hooksDir = path.join(gitDir, 'hooks');

console.log('\n🛡️  [Git Hooks Setup] Installing Pre-Commit DoD Quality Defense...');
console.log('=================================================================');

if (!fs.existsSync(gitDir)) {
  console.warn('⚠️  .git directory not found. Initialize git first with \'git init\'.');
  process.exit(0);
}

fs.mkdirSync(hooksDir, { recursive: true });
const preCommitPath = path.join(hooksDir, 'pre-commit');

const hookContent = `#!/bin/sh
# Auto-generated by project-dod-protocol
# Enforces Definition of Done (DoD) Quality Gates before commit

echo ""
echo "🛡️  [DoD Pre-Commit Gate] Verifying documentation, versions, and health..."
node scripts/verify-dod.mjs

if [ $? -ne 0 ]; then
  echo ""
  echo "❌ Commit BLOCKED by DoD Protocol. Please resolve the errors above before committing."
  echo "👉 Tip: Run 'npm run dod:check' to debug or 'npm run version:bump' if version is out of sync."
  echo ""
  exit 1
fi

echo "✨ DoD Quality Gates Satisfied. Proceeding with commit..."
echo ""
exit 0
`;

fs.writeFileSync(preCommitPath, hookContent, { encoding: 'utf-8', mode: 0o755 });

// On Windows, ensure executable attribute is set if supported
try {
  fs.chmodSync(preCommitPath, 0o755);
} catch {}

console.log('✅ Installed pre-commit hook at .git/hooks/pre-commit');
console.log('=================================================================');
console.log('✨ Git defense active: All future commits will automatically verify DoD quality gates!\n');
